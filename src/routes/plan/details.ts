/**
 * Detail records for /plan task popups. Keyed by task `id` from
 * +page.svelte. Add an entry only when there's enough substance to
 * warrant the popup; the page falls back to "no detail entry yet"
 * when missing.
 */

export interface PlanDetail {
  summary?: string;
  steps?: string[];
  acceptance?: string[];
  refs?: string[];
  /**
   * Recording of the e2e suite that verifies this task's work, per
   * CLAUDE.md Rule 12. Path is relative to /static/, e.g.
   * `/api/volume?path=test-recordings/e2e/115/routes.webm`. The Gantt popup renders an inline
   * <video controls> when set. Multiple recordings: pass the manifest
   * path instead (`/api/volume?path=test-recordings/e2e/<task>/manifest.json`) and the popup
   * lists each spec.
   *
   * Generated by: `bun run record:task -- <id>`
   * which runs `scripts/harvest_e2e_videos.ts`.
   */
  video?: string;
  videos?: string[];
  /**
   * Explicit "no recording expected" marker for docs-only or trivial
   * tasks where Rule 12's per-step e2e recording doesn't apply. Lets a
   * future reader distinguish "deliberately not recorded" from
   * "recording owed but missing".
   */
  recorded?: boolean;
}

