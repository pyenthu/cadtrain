import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const ROOT = 'src';
const SKIP = new Set(['node_modules', '.svelte-kit']);
// Count CODE files only — LOC of large generated/data JSON would swamp the
// treemap and misrepresent "where the code lives".
const EXT = new Set(['.ts', '.tsx', '.svelte', '.js', '.mjs', '.css', '.html']);
const hasCodeExt = (n) => { const i = n.lastIndexOf('.'); return i >= 0 && EXT.has(n.slice(i)); };

function countLoc(p) {
  try {
    const txt = readFileSync(p, 'utf8');
    if (!txt) return 0;
    return txt.split('\n').length;
  } catch { return 0; }
}

function walk(dir, rel) {
  const name = rel === '' ? ROOT : rel.split('/').pop();
  const path = rel === '' ? ROOT : `${ROOT}/${rel}`;
  const entries = readdirSync(dir, { withFileTypes: true })
    .filter(e => !SKIP.has(e.name) && !e.name.startsWith('.'))
    .sort((a, b) => {
      // dirs first, then alpha
      if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
      return a.name.localeCompare(b.name);
    });
  const children = [];
  for (const e of entries) {
    const full = join(dir, e.name);
    const childRel = rel === '' ? e.name : `${rel}/${e.name}`;
    if (e.isDirectory()) {
      const sub = walk(full, childRel);
      if (sub.children && sub.children.length) children.push(sub);
    } else if (hasCodeExt(e.name)) {
      children.push({ name: e.name, path: `${ROOT}/${childRel}`, loc: countLoc(full) });
    }
  }
  return { name, path, children };
}

/**
 * Walk src/, emit the /design "Folder tree" snapshot to
 * src/routes/design/folder-tree.ts, and return the stats. Exported so
 * scripts/gen-design-diagrams.mjs can drive it as one of the three regens.
 */
export function writeFolderTree() {
  const tree = walk(ROOT, '');

  // count files + total loc for the caption
  let files = 0, folders = 0, loc = 0;
  (function count(n) {
    if (n.children) { folders++; n.children.forEach(count); }
    else { files++; loc += n.loc || 0; }
  })(tree);

  const header = `// AUTO-GENERATED by scripts/gen-folder-tree.mjs — do not edit by hand.
// Snapshot of the src/ tree with per-file line counts (LOC), for the
// /design "Folder tree" hierarchy views. Regenerate with:
//   bun scripts/gen-folder-tree.mjs      (this file alone)
//   bun scripts/gen-design-diagrams.mjs  (all three /design snapshots)
// Stats at generation: ${files} files · ${folders} folders · ${loc.toLocaleString('en-US')} LOC.

export interface FolderNode {
  name: string;
  path: string;
  loc?: number;
  children?: FolderNode[];
}

export const FOLDER_TREE_STATS = { files: ${files}, folders: ${folders}, loc: ${loc} } as const;

export const FOLDER_TREE: FolderNode = ${JSON.stringify(tree, null, 2)};
`;

  writeFileSync('src/routes/design/folder-tree.ts', header);
  return { files, folders, loc };
}

// Run standalone: `bun scripts/gen-folder-tree.mjs`
if (import.meta.main) {
  const { files, folders, loc } = writeFolderTree();
  console.log(`wrote folder-tree.ts — ${files} files, ${folders} folders, ${loc} LOC`);
}
